#!/usr/bin/env node
// Regenerates the Go and TypeScript rate tables from scripts/model-rates.json.
// Run via `pnpm generate:model-rates`.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "scripts/model-rates.json");
const goPath = resolve(repoRoot, "server/internal/costrate/table.go");
const tsPath = resolve(repoRoot, "packages/core/costrate/table.ts");

const data = JSON.parse(readFileSync(jsonPath, "utf8"));
if (data.unit !== "usd_per_million_tokens" || typeof data.models !== "object") {
  throw new Error("model-rates.json: expected unit and models");
}

const keys = Object.keys(data.models).sort();
if (keys.length === 0) {
  throw new Error("model-rates.json: models is empty");
}

const models = {};
for (const key of keys) {
  const row = data.models[key];
  for (const field of ["input", "output", "cache_read", "cache_write"]) {
    if (typeof row?.[field] !== "number" || !Number.isFinite(row[field])) {
      throw new Error(`model-rates.json: ${key}.${field} must be a finite number`);
    }
    if (row[field] < 0) {
      throw new Error(`model-rates.json: ${key}.${field} must be >= 0`);
    }
  }
  models[key] = {
    input: row.input,
    output: row.output,
    cacheRead: row.cache_read,
    cacheWrite: row.cache_write,
  };
}

const hash = createHash("sha256")
  .update(JSON.stringify({ unit: data.unit, models: Object.fromEntries(keys.map((k) => [k, data.models[k]])) }))
  .digest("hex");

const header = [
  "AUTO-GENERATED by scripts/generate-model-rates.mjs.",
  "Do not edit by hand. Edit scripts/model-rates.json and run",
  "`pnpm generate:model-rates`.",
];

const goLines = [
  `// ${header[0]}`,
  `// ${header[1]}`,
  `// ${header[2]}`,
  "",
  "package costrate",
  "",
  `const CatalogHash = "${hash}"`,
  "",
  "type Rate struct {",
  "	Input      float64",
  "	Output     float64",
  "	CacheRead  float64",
  "	CacheWrite float64",
  "}",
  "",
  "var table = map[string]Rate{",
];
for (const key of keys) {
  const r = models[key];
  goLines.push(
    `\t${JSON.stringify(key)}: {Input: ${fmtNum(r.input)}, Output: ${fmtNum(r.output)}, CacheRead: ${fmtNum(r.cacheRead)}, CacheWrite: ${fmtNum(r.cacheWrite)}},`,
  );
}
goLines.push("}", "");
writeFileSync(goPath, goLines.join("\n"));

const tsLines = [
  `// ${header[0]}`,
  `// ${header[1]}`,
  `// ${header[2]}`,
  "",
  `export const CATALOG_HASH = "${hash}";`,
  "",
  "export interface ModelRate {",
  "  input: number;",
  "  output: number;",
  "  cacheRead: number;",
  "  cacheWrite: number;",
  "}",
  "",
  "export const MODEL_RATES: Readonly<Record<string, ModelRate>> = {",
];
for (const key of keys) {
  const r = models[key];
  tsLines.push(
    `  ${JSON.stringify(key)}: { input: ${fmtNum(r.input)}, output: ${fmtNum(r.output)}, cacheRead: ${fmtNum(r.cacheRead)}, cacheWrite: ${fmtNum(r.cacheWrite)} },`,
  );
}
tsLines.push("};", "");
writeFileSync(tsPath, tsLines.join("\n"));

console.log(`wrote ${keys.length} rates hash=${hash.slice(0, 12)}`);

function fmtNum(n) {
  if (Number.isInteger(n)) return String(n);
  return String(n);
}
